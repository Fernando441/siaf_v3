$("#send_carga").click(function(){

    var file_carga = document.getElementById("file_carga").value;

     if(file_carga == ""){
         Swal.fire("Para continuar debes agregar un archivo .csv");
     }else{
         Swal.fire({
             position: "top-center",
             icon: "success",
             title: "Espere un momento, la información esta siendo procesada",
             showConfirmButton: false
         });
         document.getElementById("submit_carga").submit();
     }

});

      $(".eliminar-documento").click(function() {
        var id = $(this).data('id');
        var nombre = $(this).data('nombre');

        Swal.fire({
            title: "Estas seguro de activar el registro "+nombre,
            icon: "warning",
            showCancelButton: true,
            confirmButtonText: "Si, Eliminarlo!",
            cancelButtonText: "No, Cancelar!",
            reverseButtons: true,
            confirmButtonColor: "#73ab17",
            cancelButtonColor: "#cc0c73",
        }).then(function(result) {
            if (result.value) {
                document.getElementById("id_doc_act").value = id;
                Swal.fire({
                    position: "top-center",
                    icon: "success",
                    title: "Espere un momento, la información esta siendo procesada",
                    showConfirmButton: false
                });
                document.getElementById("eliminardoc_act_form").submit();
            } else if (result.dismiss === "cancel") {
                Swal.fire(
                    "Cancelada",
                    "La acción fue cancelada",
                    "error"
                )
            }
        });
      });

